static uint8_t post_jump_hold = 0;
static float last_ref_pitch = 0.0f;
static float last_ref_roll = 0.0f;
static uint8_t ref_inited = 0;
static uint8_t tilt_confirm_cnt = 0;

static uint8_t Dino_Sensor_Jump_Triggered(void)
{
    int16_t ax, ay, az, gx, gy, gz;

    MPU6050_GetData(&ax, &ay, &az, &gx, &gy, &gz);

    float pitch = atan2((-1.0f) * (float)ax, (float)az) * 180.0f / (float)pii;
    float roll  = atan2((float)ay, (float)az) * 180.0f / (float)pii;

    if (!ref_inited)
    {
        last_ref_pitch = pitch;
        last_ref_roll  = roll;
        ref_inited = 1;
        tilt_confirm_cnt = 0;
        return 0;
    }

    if (dino_jump_flag != 0 || post_jump_hold > 0)
    {
        if (post_jump_hold > 0) post_jump_hold--;
        tilt_confirm_cnt = 0;
        last_ref_pitch = 0.7f * last_ref_pitch + 0.3f * pitch;
        last_ref_roll  = 0.7f * last_ref_roll  + 0.3f * roll;
        return 0;
    }

    /* Tang nguong len 22 do + xac nhan 2 lan lien tiep de tranh tu nhay do rung tay */
    if (fabsf(pitch - last_ref_pitch) >= 22.0f || fabsf(roll - last_ref_roll) >= 22.0f)
    {
        tilt_confirm_cnt++;
        if (tilt_confirm_cnt >= 2)
        {
            tilt_confirm_cnt = 0;
            last_ref_pitch = pitch;
            last_ref_roll  = roll;
            post_jump_hold = 18;
            return 1;
        }
    }
    else
    {
        tilt_confirm_cnt = 0;
        last_ref_pitch = 0.85f * last_ref_pitch + 0.15f * pitch;
        last_ref_roll  = 0.85f * last_ref_roll  + 0.15f * roll;
    }

    return 0;
}

void Show_Score(void)
{
    OLED_ShowNum(1,17,Score,5,6);
}

void Show_Ground(void)
{
    if(Ground_Pos<128)
    {
        for(uint8_t i=0;i<128;i++)
        {
            OLED_Buffer[7][i]=Ground[i+Ground_Pos];
        }
    }
    else
    {
        for(uint8_t i=0;i<255-Ground_Pos;i++)
        {
            OLED_Buffer[7][i]=Ground[i+Ground_Pos];
        }
        for(uint8_t i=255-Ground_Pos;i<128;i++)
        {
            OLED_Buffer[7][i]=Ground[i-(255-Ground_Pos)];
        }
    }
}

void Show_Barrier(void)
{
    if(Barrier_Pos>=143)
    {
        barrier_flag=rand()%3;
    }
    OLED_ShowImageWithReverse(127-Barrier_Pos, 44, 16, 18, Barrier[barrier_flag], 1);
    barrier.minX = (127-Barrier_Pos) + 5; 
    barrier.maxX = (127-Barrier_Pos) + 11;
    barrier.minY = 44 + 4;
    barrier.maxY = 62;
}

void Show_Cloud(void)
{
    OLED_ShowImage(127-Cloud_Pos, 9, 16, 8, Cloud);
}

void Show_Dino(uint8_t use_sensor)
{
    uint8_t jump_trigger = 0;

    if (use_sensor == 0)
    {
        uint8_t k = Key_GetNum();
        if((k == 1 || HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_1) == GPIO_PIN_RESET) && dino_jump_flag == 0)
        {
            jump_trigger = 1;
        }
    }
    else
    {
        if (Dino_Sensor_Jump_Triggered() && dino_jump_flag == 0)
        {
            jump_trigger = 1;
        }
    }

    if (jump_trigger)
    {
        dino_jump_flag = 1;
        jump_t = 0;
    }

    if (dino_jump_flag) {
        Jump_Pos = 32 * sin((float)(pii * jump_t / 1000));
    } else {
        Jump_Pos = 0;
    }
    
    uint8_t dino_base_y = 42; 
    uint8_t current_dino_y = dino_base_y - Jump_Pos;

    if(dino_jump_flag==0)
    {
        if((Ground_Pos / 8) % 2 == 0) 
            OLED_ShowImage(0, current_dino_y, 16, 18, Dino[0]);
        else 
            OLED_ShowImage(0, current_dino_y, 16, 18, Dino[1]);
    }
    else
    {
        OLED_ShowImage(0, current_dino_y, 16, 18, Dino[2]);
    }
    
    dino.minX = 0 + 4;
    dino.maxX = 16 - 4;
    dino.minY = current_dino_y + 2;
    dino.maxY = current_dino_y + 18 - 2;
}

int isColliding(struct Object_Position *a, struct Object_Position *b)
{
    if( (a->maxX > b->minX) && 
        (a->minX < b->maxX) && 
        (a->maxY > b->minY) && 
        (a->minY < b->maxY) )
    {
        OLED_Clear();
        OLED_ShowString(2, 4, "GAME  OVER", 8); 
        OLED_Update();
        HAL_Delay(1000); 
        OLED_Clear();
        OLED_Update();
        return 1;
    }
    return 0;
}

int DinoGame_Animation(uint8_t use_sensor)
{ 
    while(1)
    {
        int return_flag;
        OLED_Clear();
        Show_Ground();
        Show_Cloud();
        Show_Barrier();
        Show_Dino(use_sensor);
        Show_Score();
        OLED_Update();
        
        return_flag = isColliding(&dino, &barrier);
        if(return_flag == 1)
        {
            return 0;
        }
    }
}

void Dino_Tick(void)
{
    static uint8_t Score_Count, Ground_Count, Cloud_Count;
    Score_Count++;
    Ground_Count++;
    Cloud_Count++;

    if(Score_Count >= 100)
    {
        Score_Count = 0;
        Score++;
    }
    
    if(Ground_Count >= 20) 
    {
        Ground_Count = 0;
        Ground_Pos++;
        Barrier_Pos++;
        if(Ground_Pos >= 256) Ground_Pos = 0;
        if(Barrier_Pos >= 144) Barrier_Pos = 0;
    }
    
    if(Cloud_Count >= 50)
    {
        Cloud_Count = 0;
        Cloud_Pos++;
        if(Cloud_Pos >= 200) Cloud_Pos = 0;
    }
    
    if(dino_jump_flag == 1)
    {
        jump_t += 2;
        if(jump_t >= 1000)
        {
            jump_t = 0;
            dino_jump_flag = 0;
        }
    }
}

